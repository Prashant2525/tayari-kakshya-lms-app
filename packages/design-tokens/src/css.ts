import { elevation, fontFamily, motion, radius, themes, type SemanticColors } from './tokens.js';

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);

function colorVars(colors: SemanticColors): string {
  return Object.entries(colors)
    .map(([name, value]) => `  --tk-${kebab(name)}: ${value};`)
    .join('\n');
}

/**
 * CSS custom properties for web surfaces. Light by default; dark via `prefers-color-scheme` unless the page
 * forces a theme with `data-theme="light|dark"` on <html>.
 */
export function buildCss(): string {
  const shared = [
    `  --tk-font-sans: ${fontFamily.sans};`,
    ...Object.entries(radius).map(([k, v]) => `  --tk-radius-${k}: ${v}px;`),
    ...Object.entries(elevation).map(([k, v]) => `  --tk-shadow-${k}: ${v};`),
    `  --tk-duration-fast: ${motion.fast}ms;`,
    `  --tk-duration-base: ${motion.base}ms;`,
    `  --tk-duration-slow: ${motion.slow}ms;`,
    `  --tk-easing-standard: ${motion.easingStandard};`,
  ].join('\n');

  return `/* Generated by @tk/design-tokens — do not edit. */
:root {
${shared}
${colorVars(themes.light)}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${colorVars(themes.dark)}
    color-scheme: dark;
  }
}
:root[data-theme='dark'] {
${colorVars(themes.dark)}
  color-scheme: dark;
}
`;
}
